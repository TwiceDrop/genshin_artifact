// Builds the character list that usage stats accepts, from the release character catalog and its Chinese names.
// Run `node beta-tools/usage-stats-characters.mjs` after the catalog changes; tests/usage-stats-characters.test.mjs
// fails while server/usage-stats-characters.mjs is out of date.
import fs from 'node:fs'
import path from 'node:path'
import {fileURLToPath} from 'node:url'
import catalog from '../src/assets/_gen_character.js'

const root = fileURLToPath(new URL('..', import.meta.url))
export const USAGE_STATS_CHARACTERS_FILE = path.join(root, 'server', 'usage-stats-characters.mjs')

export function buildUsageStatsCharacters() {
    const zh = JSON.parse(fs.readFileSync(path.join(root, 'src', 'i18n', 'generated', 'zh-cn.json'), 'utf8'))
    return Object.values(catalog).map(c => {
        const name = zh[c.nameLocale]
        if (!name) throw new Error(`角色 ${c.name} 缺少中文名（nameLocale ${c.nameLocale}）`)
        return [c.name, name]
    }).sort(([a], [b]) => a.localeCompare(b, 'en'))
}

export function renderUsageStatsCharacters(rows) {
    return `// Generated by beta-tools/usage-stats-characters.mjs from src/assets/_gen_character.js; do not edit by hand.
// Usage stats accepts only these character ids. Shared by the client, online-service and the stats page.
const ROWS = ${JSON.stringify(rows)}

const BY_NAME = new Map(ROWS.map(([name, zh]) => [name, Object.freeze({name, zh})]))
export const listUsageCharacters = () => [...BY_NAME.values()]
export const getUsageCharacter = name => BY_NAME.get(name)
`
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const rows = buildUsageStatsCharacters()
    fs.writeFileSync(USAGE_STATS_CHARACTERS_FILE, renderUsageStatsCharacters(rows))
    console.log(`wrote ${rows.length} characters to ${path.relative(root, USAGE_STATS_CHARACTERS_FILE)}`)
}
