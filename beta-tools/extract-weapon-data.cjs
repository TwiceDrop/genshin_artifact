// Read numeric game data from saved pages; never execute downloaded scripts.
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const parser = require('@babel/parser');
process.chdir(path.resolve(__dirname, '..'));
function value(node) {
    if (['NumericLiteral','StringLiteral','BooleanLiteral'].includes(node.type)) return node.value;
    if (node.type === 'NullLiteral') return null;
    if (node.type === 'UnaryExpression' && node.operator === '-') return -value(node.argument);
    if (node.type === 'ArrayExpression') return node.elements.map(value);
    if (node.type === 'ObjectExpression') return Object.fromEntries(node.properties.map(p => [p.key.name ?? p.key.value, value(p.value)]));
    throw Error('Nonliteral data: ' + node.type);
}
const weapons = [];
for (const [id, name, slug] of [[11522,'BeyondTheChrysalis','beyond-the-chrysalis'],[14524,'HymnOfTheMaelstrom','hymn-of-the-maelstrom']]) {
    const html = fs.readFileSync(`beta-data/sources-beta3/${id}.html`, 'utf8');
    const found = {curves:{}};
    function visit(node) {
        if (!node || typeof node !== 'object') return;
        if (node.type === 'ObjectExpression') {
            const props = Object.fromEntries(node.properties.filter(p => p.type === 'ObjectProperty').map(p => [p.key.name ?? p.key.value, p.value]));
            if (props.refinements && props.attributes && props.promotions) {
                for (const key of ['attributes','promotions','refinements']) found[key] = value(props[key]);
            }
            if (props.operation && props.values && props.id) found.curves[value(props.id)] = value(props.values);
        }
        for (const [key, child] of Object.entries(node)) if (!['loc','start','end'].includes(key)) {
            if (Array.isArray(child)) child.forEach(visit); else if (child && typeof child === 'object') visit(child);
        }
    }
    for (const match of html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)) if(match[1].includes('refinements:')) visit(parser.parse(match[1], {sourceType:'unambiguous'}));
    if (!found.refinements || !found.curves[2301]) throw Error('Missing weapon data: ' + id);
    const rows = [];
    for (let level = 1; level <= 90; level++) {
        for (const ascend of [false, ...([20,40,50,60,70,80].includes(level) ? [true] : [])]) {
            const promotion = found.promotions.findIndex(p => level < p.maximum_level || (level === p.maximum_level && !ascend));
            const base = found.attributes.find(a => a.attribute_id === 4);
            const sub = found.attributes.find(a => a.attribute_id !== 4);
            const addition = found.promotions[promotion].stat_additions.find(s => s.stat_id === 4)?.value || 0;
            rows.push({level, ascend, attack:Math.round(base.value * found.curves[base.curve_id][level-1] + addition), subStat:Number((sub.value * found.curves[sub.curve_id][level-1]).toFixed(4))});
        }
    }
    weapons.push({id, name, url:`https://gi.gachabase.net/weapons/${id}/${slug}/beta?lang=chs`, sha256:crypto.createHash('sha256').update(html).digest('hex'), refinements:found.refinements.map(r => r.parameters), levels:rows});
}
fs.writeFileSync('beta-data/weapons-beta3.json', JSON.stringify({checkedAt:new Date().toISOString(), revision:'7.0.54 D48100502', weapons},null,2)+'\n');
let rust = '// Generated by beta-tools/extract-weapon-data.cjs from saved game-data pages.\nuse crate::weapon::WeaponName;\npub fn stats(name: WeaponName, level: i32, ascend: bool) -> Option<(f64,f64)> {\n let index=(level.clamp(1,90)-1) as usize;\n let promotion=[20,40,50,60,70,80].iter().filter(|&&l| level>l || (level==l && ascend)).count();\n let (base,sub)=match name {\n';
for (const w of weapons) {
    // Separate per-level attack from promotion adds so all 1..90 levels remain exact.
    // Use both pre/post-ascension tables: game rounding can differ by one at a boundary.
    const pre = w.levels.filter(r=>!r.ascend);
    const post = w.levels.filter(r=>r.ascend);
    rust += `WeaponName::${w.name} => {\n let atk:[f64;90]=[${pre.map(r=>r.attack+'.0').join(',')}];\n let sub:[f64;90]=[${pre.map(r=>r.subStat.toFixed(4)).join(',')}];\n let extra=if ascend { match level {${post.map(r=>r.level+' => '+(r.attack-pre[r.level-1].attack)+'.0').join(',')}, _=>0.0} } else {0.0};\n (atk[index]+extra,sub[index])\n },\n`;
}
rust += '_ => return None,\n };\n Some((base,sub))\n}\n';
rust = rust.replace(' let promotion=[20,40,50,60,70,80].iter().filter(|&&l| level>l || (level==l && ascend)).count();\n','');
fs.writeFileSync('mona_core/src/weapon/signature_stats.rs', rust);
