import {nativeGraphImports,bindNativeGraphMemory} from '../../beta-data/team-dps-graph-reader.mjs';
import {progressImports} from '../../beta-data/optimizer-progress.mjs';
import {createPreview7201Facade} from '../../beta-data/preview-7201-facade.mjs';
import {withDirectReactionScope} from '../../beta-data/direct-reaction-scope.mjs';
import {withLegacyEnemyBridge} from '../../beta-data/enemy-interface.mjs';
import {withInterfaceContracts} from '../../beta-data/interface-contracts.mjs';
import {withLegacyEffectBridge} from '../../beta-data/legacy-effect-bridge.mjs';
import * as bridge from '../../mona_wasm/pkg/mona_wasm_bg.js';
import {withLunarDamageContexts} from '../../beta-data/lunar-context-facade.mjs';
import { bindings } from '../../mona_wasm/pkg/bindings.js';
import initExtension, * as extension from '../../beta-data/team-dps-native/extension-bindings.mjs';
import { createBeta2 } from '../../beta-data/vesna-facade.mjs';
import { createFacade } from '../../beta-data/facade.mjs';
import { createLimitedWeaponFacade } from '../../beta-data/limited-weapon-facade.mjs';
import { createStrengthenedFacade } from '../../beta-data/strengthened-facade.mjs';
import { createStellarSupportFacade } from '../../beta-data/stellar-support-facade.mjs';
import { withHybridTeamOptimization } from '../../beta-data/hybrid-team-optimizer.mjs';
import { createExpandedWeaponsFacade } from '../../beta-data/expanded-weapons.mjs';
import { withLumineTraveler } from '../../beta-data/lumine-traveler-facade.mjs';
import weaponData from '../../beta-data/weapons-release-71.json';
import signatureData from '../../beta-data/weapons-signature-release-71.json';
import data from '../../beta-data/vodyanitsa.json';
import support from '../../beta-data/extension-support.json';
import characters from '../../src/assets/_gen_character.js';
const response = await fetch(new URL('../../beta-data/team-dps-native/native-graph.wasm?raw-wasm', import.meta.url));
const { instance } = await WebAssembly.instantiate(await response.arrayBuffer(), { './mona_wasm_bg.js': bridge, mona_trace:nativeGraphImports, mona_progress:progressImports(()=>instance.exports.memory) });
bindNativeGraphMemory(()=>instance.exports.memory);
bindings.lI(instance.exports);
const extensionResponse = await fetch(new URL('../../beta-data/team-dps-native/extension-graph.wasm?raw-wasm', import.meta.url));
await initExtension(await extensionResponse.arrayBuffer());
const rawOriginalApi = {BonusPerStat:bindings.bd,CalcArtifactBestSet:bindings.uC,CalculatorInterface:bindings.K2,
CommonInterface:bindings.Ps,DSLInterface:bindings.ZB,OptimizeSingleWasm:bindings.E2,PotentialInterface:bindings.gF,
TeamOptimizationWasm:bindings.B8,TransformativeDamage:bindings.PX};
const originalApi = withLegacyEffectBridge(withLegacyEnemyBridge(rawOriginalApi,instance.exports),instance.exports);
const baseApi = createFacade(originalApi,extension,data,support,characters);
const stellar = createStellarSupportFacade(createLimitedWeaponFacade(createBeta2(baseApi,extension,support),originalApi,weaponData,signatureData),originalApi);
const strengthened = createStrengthenedFacade(stellar.facade,stellar.transformStellarTarget);
const api = withInterfaceContracts(withDirectReactionScope(withLunarDamageContexts(withLumineTraveler(withHybridTeamOptimization(createExpandedWeaponsFacade(createPreview7201Facade(strengthened,extension),originalApi,extension))))));
export const {BonusPerStat,CalcArtifactBestSet,CalculatorInterface,CommonInterface,DSLInterface,OptimizeSingleWasm,PotentialInterface,TeamOptimizationWasm,TransformativeDamage}=api;
